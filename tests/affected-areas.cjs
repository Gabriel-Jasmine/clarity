const assert=require('assert');
const {boot}=require('./helpers/boot.cjs');
let b=boot();
const r=code=>b.run(code);
const plain=code=>JSON.parse(JSON.stringify(r(code)));
const tick=(id,checked)=>{const control=b.doc.querySelectorAll('[data-stake]').find(e=>e.value===id);assert(control);control.checked=checked;control.onchange();};
const raw='  Custom <area> & "details"  ';
r('step=1;data.priorities=["work"];data.hasHardBoundaries="no";render()');
assert.equal(r('data.stakesOtherText'),'');
assert(b.doc.querySelector('#stake-other-detail').hidden);
assert(/id="stake-other-text"[^>]*disabled/.test(r('boundaries()')));
assert.equal(b.doc.querySelectorAll('[data-stake]').length,10);
assert.equal(b.doc.querySelectorAll('[data-priority]').length,9);
tick('other',true);
assert(!b.doc.querySelector('#stake-other-detail').hidden);
assert(!b.doc.querySelector('#stake-other-text').disabled);
assert(r('assessmentMissing().some(item=>item.step===1&&item.reason==="Some required answers are missing")'),'An unspecified Other remains incomplete');
const input=b.doc.querySelector('#stake-other-text');input.value=raw;input.oninput();
assert(!r('assessmentMissing().some(item=>item.step===1&&item.reason==="Some required answers are missing")'),'A specified Other can be the only selected area');
assert(r('affectedAreaLabels()[0]')==='Other — '+raw);
assert(r('decisionOverview()').includes('Custom &lt;area&gt; &amp; &quot;details&quot;'));
assert(r('boundaries()').includes('Custom &lt;area&gt; &amp; &quot;details&quot;'));
assert(r('decisionContextText()').split('## What is at stake in this decision')[1].split('##')[0].includes(raw));
let record=plain('captureRecords().find(r=>r.field==="stakesOtherText")');
assert.equal(record.questionId,'Q78');assert.equal(record.section,'Things Dear to You');assert.equal(record.value,raw);assert.equal(record.scope,'current');assert(record.visible&&record.required);assert.equal(record.state,'written');
r('data.reviewed=[1];save()');
assert(r('data.reviewed.includes(1)'));
input.value=raw+' changed';input.oninput();assert(!r('data.reviewed.includes(1)'),'Editing active writing invalidates its review');
input.value=raw;input.oninput();
tick('financial',true);
b=b.reload();
assert.deepEqual(plain('data.stakes'),['other','financial']);
assert.equal(r('data.stakesOtherText'),raw);
assert(!b.doc.querySelector('#stake-other-detail').hidden);
assert(!r('data.priorities.includes("financial")'),'Affected areas are independent of top priorities across reload');
tick('other',false);
assert(b.doc.querySelector('#stake-other-detail').hidden);
assert(b.doc.querySelector('#stake-other-text').disabled);
assert.equal(r('data.stakesOtherText'),raw);
assert(!r('decisionOverview()').split('<section class="ai-export">')[0].includes('Custom &lt;area&gt;'));
assert(!r('decisionContextText()').split('## Capture records')[0].includes(raw));
assert(!plain('captureRecords().filter(r=>r.scope==="current")').some(record=>typeof record.value==='string'&&record.value.includes(raw)));
record=plain('captureRecords().find(r=>r.field==="stakesOtherText:retained")');
assert.equal(record.value,raw);assert.equal(record.scope,'inactive');assert(!record.visible&&!record.required);
r('data.reviewed=[1];save();data.stakesOtherText+=" inactive edit";save()');
assert(r('data.reviewed.includes(1)'),'An inactive draft is excluded from review identity');
b=b.reload();tick('other',true);assert.equal(r('data.stakesOtherText'),raw+' inactive edit');
assert(!r('data.reviewed.includes(1)'),'Restoring the answer invalidates its review');
const legacy=plain('data');delete legacy.stakesOtherText;legacy.stakes=['work','financial'];legacy.ui.step=1;
b=boot(legacy);assert.equal(r('data.stakesOtherText'),'');assert.deepEqual(plain('data.stakes'),['work','financial']);
console.log('Passed: affected-area Other selection, completion, escaping, active/inactive capture, exact writing restoration, independent area persistence and review invalidation.');
